#运算符 + - * / // % **
print("10 + 4 = ",10 + 4)#加
print("10 - 4 = ",10 - 4)#减
print("10 * 4 = ",10 * 4)#乘
print("10 / 4 = ",10 / 4)#除
print("10 // 4 = ",10 // 4)#整除（结果为整数）
print("10 % 4 = ",10 % 4)#取余/求模
print("10 ** 4 = ",10 ** 4)#幂指数
#运算符优先级：**------> * / // % -------> + -
